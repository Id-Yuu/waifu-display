  async fetchCharacterData(characterPath) {
    const input = characterPath.trim();

    // 1. Direct URL case
    if (input.startsWith('http')) {
      const filename = input.split('/').pop();
      const name = filename.replace(/\.[^.]+$/, '').toLowerCase();
      const match = this.characterList.find(c => c.name === name);
      return {
        characterId: name,
        imageUrl: input,
        characterPath: filename,
        provider: 'pgr',
        displayName: match ? match.displayName : filename.replace(/\.[^.]+$/, '')
      };
    }

    const lowerTerm = input.toLowerCase();

    // 2. Exact list match
    const match = this.characterList.find(c =>
      c.name === lowerTerm ||
      c.displayName.toLowerCase() === lowerTerm ||
      c.filename.toLowerCase() === lowerTerm
    );

    if (match) {
      return {
        characterId: match.name,
        imageUrl: `${this.baseUrl}/${match.filename}`,
        characterPath: match.filename,
        provider: 'pgr',
        displayName: match.displayName
      };
    }

    // 3. Partial list match
    const partialMatch = this.characterList.find(c =>
      c.name.includes(lowerTerm) ||
      c.displayName.toLowerCase().includes(lowerTerm)
    );

    if (partialMatch) {
      return {
        characterId: partialMatch.name,
        imageUrl: `${this.baseUrl}/${partialMatch.filename}`,
        characterPath: partialMatch.filename,
        provider: 'pgr',
        displayName: partialMatch.displayName
      };
    }

    throw new Error(`Character "${characterPath}" not found. Try selecting from the list.`);
  },

  async searchCharacters(query) {
    const searchTerm = query?.toLowerCase().trim() || '';

    if (!searchTerm) {
      return this.characterList.map(char => ({
        name: char.name,
        displayName: char.displayName,
        imageUrl: `${this.thumbnailBase}/${char.filename}`,
        filename: char.filename
      }));
    }

    const results = this.characterList.filter(char => {
      const searchable = `${char.name} ${char.displayName}`.toLowerCase();
      return searchable.includes(searchTerm);
    });

    return results.map(char => ({
      name: char.name,
      displayName: char.displayName,
      imageUrl: `${this.thumbnailBase}/${char.filename}`,
      filename: char.filename
    }));
  },

