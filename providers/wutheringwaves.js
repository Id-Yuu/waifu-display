    let searchTerm = characterPath.trim();

    // 1. Direct URL case
    if (searchTerm.startsWith('http')) {
      if (await verifyImage(searchTerm)) {
        const filename = searchTerm.split('/').pop();
        const name = filename.replace(/\.[^.]+$/, '').split('-')[0];
        return {
          characterId: name,
          imageUrl: searchTerm, // Use the provided valid URL
          characterPath: filename,
          provider: 'wutheringwaves',
          displayName: this.displayNames[name] || name
        };
      }
      throw new Error(`Image not found at URL: ${searchTerm}`);
    }

    // 2. Direct filename case
    if (searchTerm.includes('.')) {
      const testUrl = `${this.baseUrl}/${searchTerm}`;
      if (await verifyImage(testUrl)) {
        const name = searchTerm.replace(/\.[^.]+$/, '').split('-')[0];
        return {
          characterId: name,
          imageUrl: testUrl, // Dynamically set using baseUrl
          characterPath: searchTerm,
          provider: 'wutheringwaves',
          displayName: this.displayNames[name] || name
        };
      }
      throw new Error(`File not found: ${searchTerm}`);
    }

    const lowerTerm = searchTerm.toLowerCase();

    // 3. Exact list match
    const match = this.characterList.find(c => 
      c.name === lowerTerm || 
      c.displayName.toLowerCase() === lowerTerm
    );

    if (match) {
      return {
        characterId: match.name,
        imageUrl: `${this.baseUrl}/${match.filename}`, // Dynamically generated
        characterPath: match.filename,
        provider: 'wutheringwaves',
        displayName: match.displayName
      };
    }

    // 4. Partial list match
    const partialMatch = this.characterList.find(c => 
      c.name.includes(lowerTerm) || 
      c.displayName.toLowerCase().includes(lowerTerm)
    );

